// Deep-merge a translation partial over the typed default, key by key.
// Arrays are merged by index (same convention as mergeList in homepage.ts).
// Only defined leaf values in `patch` override; everything else falls
// through to `base`, which keeps hrefs/images/icons/slugs/numbers intact.
function deepMerge<T>(base: T, patch: unknown): T {
  if (patch == null) return base;
  if (Array.isArray(base)) {
    if (!Array.isArray(patch)) return base;
    return base.map((item, i) => (i < patch.length ? deepMerge(item, patch[i]) : item)) as unknown as T;
  }
  if (base !== null && typeof base === "object" && typeof patch === "object") {
    const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
    for (const key of Object.keys(patch as Record<string, unknown>)) {
      out[key] = deepMerge(out[key], (patch as Record<string, unknown>)[key]);
    }
    return out as T;
  }
  // Leaf: string/number override.
  return (patch as T) ?? base;
}

